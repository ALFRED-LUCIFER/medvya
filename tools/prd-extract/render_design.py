"""Render design reference docs (docs/02-design/*.md) from Foundations and Handoff data.

Run: python3 -I tools/prd-extract/render_design.py  (from repo root)
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
F = json.load(open(os.path.join(ROOT, "docs/02-design/data/foundations.json")))
H = json.load(open(os.path.join(ROOT, "docs/02-design/data/handoff.json")))
OUT = os.path.join(ROOT, "docs/02-design")
HEADER = "<!-- GENERATED by tools/prd-extract/render_design.py from the design files. Do not edit by hand. -->\n\n"


def esc(s):
    return str(s).replace("|", "\\|").replace("\n", " ")


def write(name, text):
    with open(os.path.join(OUT, name), "w") as f:
        f.write(HEADER + text + "\n")


# ---------- tokens ----------
L = ["# Design tokens (Foundations §02–§04)\n",
     "## Colour tokens (light / dark, contrast on white)\n",
     "| Token | Light | Dark | Contrast | Use |\n|---|---|---|---|---|"]
for c in F["colors"]:
    L.append(f"| `{c['token']}` | `{c['hex']}` | `{c['dark']}` | {c['ratio']} | {c['use']} |")
L.append("\n## Module groupings\n\nUsed as a 3px nav rail tint and section label, **never as page fills**.\n")
L.append("| Module | Icon | Tint | Line | Ink | Scope | Design phase |\n|---|---|---|---|---|---|---|")
for m in F["modules"]:
    L.append(f"| {m['name']} | `{m['icon']}` | `{m['tint']}` | `{m['line']}` | `{m['ink']}` | {m['desc']} | {m['phase']} |")
L.append("\n## Type scale (Manrope; JetBrains Mono for IDs and codes; tabular numbers for clinical values)\n\n| Style | Spec |\n|---|---|")
for t in F["typeScale"]:
    L.append(f"| {t['name']} | {t['spec']} |")
L.append("\n## Spacing (8px base)\n\n| Token | px |\n|---|---|")
for s in F["spacing"]:
    L.append(f"| `{s['token']}` | {s['px']} |")
L.append("""
## Radius, elevation, layout

- Radius: 6 · 10 (MUI `shape.borderRadius`) · 12 (cards) · pill
- Elevation: e0 border only · e1 popover · e2 modal. 1px borders, almost no shadow, no neon glow.
- Breakpoints: xs 360 · md 768 · lg 1280 · xl 1600. Max content width 1440 at widescreen.
- Touch targets ≥ 44px (48px in the patient portal). Icons 20/24px, Material Symbols Outlined.
- Motion 160ms ease-out. Respects `prefers-reduced-motion`. RTL-ready logical properties for Arabic.

## Dark mode accents (Mobile & Tablet X-02)

Canvas `#0F1C2A`, cards `#12202E`, ink `#E6EDF3`, ink2 `#9DB0C2`, line `#22364A`, teal `#2BB3A3`, blue `#6B9BFF`, AI `#A08CF0` (AI stays dashed), red `#F47A86`, ok `#4CC79C`. Red and amber keep their text labels.

High contrast: 2px borders, no tints, underlined links.
""")
L.append("## Closed-loop result states (each has its own icon and label)\n\n| State | Icon | Bg | Fg |\n|---|---|---|---|")
for s in F["loop"]:
    L.append(f"| {s['label']} | `{s['icon']}` | `{s['bg']}` | `{s['fg']}` |")
L.append("""
## Clinical status primitives

- **Provenance tags:** `auto_awesome` AI draft · not reviewed (violet, dashed) · `verified` Clinician verified · `person` Patient reported · `sync_alt` Synced from HIS · `lock` Signed · read-only. The gap analysis adds **Imported** and **Unverified · patient upload**.
- **Alerts, with severity in words:** `error` Critical · unacknowledged · `warning` Attention · uncertain · `info` Info.
- **Recording and consent:** REC mm:ss (red) · Paused · Recording consent · given · Declined · manual note.
- **Patient identity banner, fixed on every clinical screen:** name, age, sex, MRN, DOB, allergies (never collapsed), consent state, encounter date and location, plus a SYNTHETIC marker in demo data.
- **Buttons:** primary / secondary / AI / destructive / disabled. Focus ring is 2px `#2563EB` with a 2px offset. A disabled sign button states the count, e.g. "Approve (2 unresolved)".
""")
write("tokens.md", "\n".join(L))

# ---------- components + theme + microcopy + a11y (handoff) ----------
L = ["# Component states, MUI theme, microcopy, accessibility (Handoff)\n", "## 1 · Component states\n"]
for c in H["comps"]:
    L.append(f"### {c['n']} — `{c['mui']}`\n\n| State | Label | Height | Radius | Border | Bg | Fg | Outline | Icon |\n|---|---|---|---|---|---|---|---|---|")
    for v in c["states"]:
        L.append(f"| {v['k']} | {esc(v['t'])} | {v['h']} | {v['r']} | {esc(v['b'])} | `{v['bg']}` | `{v['fg']}` | {esc(v['ol'])} | {v['icon'] or '—'} |")
    L.append("")
L.append("## 2 · MUI theme (excerpt, verbatim)\n\n```ts\n" + H["themeCode"] + "\n```\n")
L.append("## 4 · Microcopy (testable, use these exact strings)\n\n| Key | Text |\n|---|---|")
for m in H["copy"]:
    L.append(f"| `{m['k']}` | {esc(m['v'])} |")
L.append("\n## 5 · Accessibility checklist (WCAG 2.2 AA)\n")
L += [f"- [ ] {a['t']}" for a in H["a11y"]]
L.append("\n## 6 · ERD additions required by the designs\n\n| Entity | Columns | Used by |\n|---|---|---|")
for e in H["erd"]:
    L.append(f"| `{e['n']}` | {esc(e['cols'])} | {e['by']} |")
write("components-theme-copy.md", "\n".join(L))

# ---------- sitemap + permission matrix + routes ----------
L = ["# Role sitemap, permission matrix and routes\n", "## Role-based sitemap (Foundations §05)\n"]
for r in F["sitemap"]:
    L.append(f"### {r['role']} — {r['shell']}\n\n| Screen | Route | Design phase |\n|---|---|---|")
    for x in r["routes"]:
        L.append(f"| {x['label']} | `{x['path']}` | {x['phase']} |")
    L.append("")
L.append("## Role-permission matrix (Foundations §06)\n")
L.append("Access is tenant + facility + role + care relationship + purpose. Break-glass grants temporary read with a typed justification and post-hoc review. **Receptionists never see clinical notes. Patients never see unreviewed AI output.**\n")
L.append("| Capability | " + " | ".join(F["roles"]) + " |\n|---|" + "---|" * len(F["roles"]))
for row in F["matrix"]:
    L.append(f"| {row['cap']} | " + " | ".join(c["v"] for c in row["cells"]) + " |")
L.append("\nLegend: Full · Read · Own (own records only) · Limited · Sign (can sign/approve) · Released (patient sees only released items) · Config · Break-glass · — (no access)\n")
L.append("## Routes ↔ guards ↔ Figma frames (Handoff §3)\n\n| Route | Guard | Figma frame | Design file |\n|---|---|---|---|")
for r in H["routes"]:
    L.append(f"| `{r['p']}` | {r['g']} | {r['f']} | {r['file']} |")
write("sitemap-and-permissions.md", "\n".join(L))

# ---------- screen inventory + ERD coverage + state machines ----------
L = ["# Screen inventory (Foundations §07)\n",
     f"{F['totalCount']} inventory rows · {F['doneCount']} hi-fi · {F['pendingCount']} hi-fi open. Design phases M1–M4 are pre-PRD labels; see [../01-prd/traceability.md](../01-prd/traceability.md) for the PRD v2 phase of each screen.\n",
     "> Known issue (PRD v2 finding): P-09 is used for both \"Doctor revenue & payout report\" and \"Receipt/tax invoice print\", and P-10–P-14 are listed twice. PRD v2 renumbers receipts to **P-15**. Tickets use P-15.\n",
     "| ID | Screen | Module | Roles | Route | Design phase | Status |\n|---|---|---|---|---|---|---|"]
seen = set()
for s in F["screens"]:
    key = (s["id"], s["name"])
    if key in seen:
        continue
    seen.add(key)
    L.append(f"| {s['id']} | {esc(s['name'])} | {s['mod']} | {esc(s['roles'])} | `{s['route']}` | {s['phase']} | {s['status']} |")
L.append(f"\n# Architecture & ERD coverage (Foundations §08)\n\n{F['erdCount']} entities. Each one is mapped to a screen or marked backend-only.\n")
for g in F["erd"]:
    L.append(f"\n## {g['name']}\n\n| Entity | Screens |\n|---|---|")
    for r in g["rows"]:
        L.append(f"| `{r['e']}` | {esc(r['s'])} |")
L.append("\n# State machines (Foundations §08)\n")
for m in F["machines"]:
    L.append(f"## {m['name']}\n\n`" + "` → `".join(x["t"] for x in m["states"]) + f"`\n\nWhere: {m['where']}\n")
write("screen-inventory-and-erd-coverage.md", "\n".join(L))
print("ok")
