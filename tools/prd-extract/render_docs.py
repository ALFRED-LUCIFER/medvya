"""Render PRD v2 reference tables (docs/01-prd/*.md) from docs/01-prd/data/prd-v2.json.

Run: python3 -I tools/prd-extract/render_docs.py  (from repo root)
"""
import datetime as dt
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
D = json.load(open(os.path.join(ROOT, "docs/01-prd/data/prd-v2.json")))
OUT = os.path.join(ROOT, "docs/01-prd")
WEEK1 = dt.date(2026, 10, 26)  # planning assumption, see roadmap.md


def wk_start(n):
    return WEEK1 + dt.timedelta(weeks=n - 1)


def wk_end(n):
    return wk_start(n) + dt.timedelta(days=4)


def fmt(d):
    return d.strftime("%d %b %Y")


def esc(s):
    return str(s).replace("|", "\\|").replace("\n", " ")


def write(name, text):
    with open(os.path.join(OUT, name), "w") as f:
        f.write(text)


HEADER = "<!-- GENERATED by tools/prd-extract/render_docs.py from PRD v2 data. Do not edit by hand. -->\n\n"

# ---------- requirements catalogue ----------
lines = [HEADER, "# Requirement catalogue (PRD v2, verbatim)\n",
         "Requirement IDs are stable and must be used in tickets, tests and release notes (PRD v2 §04). "
         "`ADDED v2` marks requirements that no earlier source had. `DESIGN NEEDED` marks screens with no design yet (N-xx).\n"]
for p in D["phases"]:
    lines.append(f"\n## {p['code']} · {p['name']}\n")
    lines.append(f"- **Weeks:** {p['weeks']} · **Release:** {p['rel']}")
    lines.append(f"- **Delivered to:** {p['to']}")
    lines.append(f"- **Day one:** {p['dayOne']}")
    lines.append(f"- **Goal:** {p['goal']}\n")
    lines.append("| ID | Requirement | Priority | Screens | Flags |\n|---|---|---|---|---|")
    for f in p["feats"]:
        scr = ", ".join(s["id"] for s in f["scr"]) or "—"
        flags = " ".join(x for x, on in (("ADDED v2", f["added"]), ("DESIGN NEEDED", f["need"])) if on)
        lines.append(f"| **{f['id']}** | **{esc(f['t'])}.** {esc(f['d'])} | {f['pr']} | {scr} | {flags} |")
    lines.append("\n**Platform & non-functional**\n")
    lines += [f"- {x}" for x in p["nfr"]]
    lines.append("\n**Exit criteria (release gate)**\n")
    lines += [f"- [ ] {x}" for x in p["exit"]]
    lines.append("\n**Delivery package**\n")
    lines += [f"- {x}" for x in p["pkg"]]
    lines.append("\n**Dependencies & risks**\n")
    lines += [f"- {x}" for x in p["deps"]]
    lines.append(f"\n**Not in this phase:** {p['notIn']}\n")
write("requirements-catalogue.md", "\n".join(lines) + "\n")

# ---------- roadmap with calendar ----------
lines = [HEADER, "# Roadmap and delivery ladder\n",
         "Weeks assume one full-time developer with AI coding help, using the screens already designed. "
         "Phases overlap on purpose: the next phase starts while the previous release is in pilot. "
         "Dates are planning targets, not promises. Regulator onboarding and hospital procurement are outside our control.\n",
         f"> **Calendar assumption:** Week 1 starts **Monday {fmt(WEEK1)}** (the first Monday after PRD v2, dated 20 Oct 2026). "
         "To move the plan, change `WEEK1` in `tools/prd-extract/render_docs.py` and `tools/tickets/build.py`, then regenerate.\n",
         "| Phase | Name | Weeks | Start | End | Release | Delivered to |\n|---|---|---|---|---|---|---|"]
for p in D["phases"]:
    s, e = p["s"], p["e"]
    lines.append(f"| {p['code']} | {p['name']} | {p['weeks']} | {fmt(wk_start(s))} | {fmt(wk_end(e))} | {p['rel']} | {esc(p['to'])} |")
lines.append("\n## Milestones\n\n| Milestone | Week | Target date (Friday) |\n|---|---|---|")
for t, w in [("Internal demo", 3), ("First real bookings", 10), ("First signed AI note", 18), ("First paying clinic", 29), ("v1.0 GA", 32), ("First hospital", 60)]:
    lines.append(f"| {t} | {w} | {fmt(wk_end(w))} |")
lines.append("\n## What each recipient can do on day one\n\n| Phase | Release | Day one |\n|---|---|---|")
for p in D["phases"]:
    lines.append(f"| {p['code']} | {p['rel']} | {esc(p['dayOne'])} |")
lines.append("\n## Calendar risks spotted while dating the plan\n")
lines.append("- **P1 (16 Nov 2026 – 01 Jan 2027) runs through the year-end holidays.** The exit criterion "
             "\"2 consecutive weeks of real bookings\" may slip if partner clinics run reduced hours. Plan the pilot weeks for early January if needed.")
lines.append("- **P2 and P3 overlap P1/P2 pilots** (weeks 9–10 and 13–15). With one developer, overlap is only safe while the previous phase is in pilot (bug-fix mode), as PRD v2 intends.")
lines.append("- **P7 (weeks 36–60) depends on hospital procurement**, so its dates are the least certain.")
write("roadmap.md", "\n".join(lines) + "\n")

# ---------- cross-cutting, metrics, stack, process ----------
lines = [HEADER, "# Cross-cutting requirements (definition of done for every feature)\n",
         "A feature that misses one of these is not shippable (PRD v2 §05).\n"]
for g in D["nfr"]:
    lines.append(f"\n## {g['id']} · {g['t']}\n")
    lines += [f"- {x}" for x in g["pts"]]
lines.append("\n# Success metrics\n\nMeasured from pilot onward. Baselines are captured at each partner clinic in P1 before Medvya changes their workflow. Clinical outcomes are not claimed.\n")
lines.append("| Metric | Target | From | How measured |\n|---|---|---|---|")
for m in D["metrics"]:
    lines.append(f"| {esc(m['m'])} | {esc(m['t'])} | {m['p']} | {esc(m['h'])} |")
lines.append("\n# Release and delivery process\n")
for s in D["process"]:
    lines.append(f"{s['n']}. **{s['t']}.** {s['d']}")
lines.append("\n- **Environments:** Local (Docker Compose) → preview per pull request → staging (synthetic data) → production per country. Production deploys only from tagged releases on protected main.")
lines.append("- **Feature flags:** every phase ships behind per-tenant flags. Pilot clinics receive features before general availability. A flag can be turned off without a redeploy.")
lines.append("- **Versioning:** R0–R4 are pilot releases (0.x). R5 is v1.0 general availability. Later phases ship as minor versions. Database migrations are forward-only and reviewed.")
write("cross-cutting-metrics-process.md", "\n".join(lines) + "\n")

# ---------- risks, decisions ----------
lines = [HEADER, "# Risks, open decisions and postponed scope\n", "| Risk | Impact | Mitigation | Phase |\n|---|---|---|---|"]
for r in D["risks"]:
    lines.append(f"| {esc(r['r'])} | {r['i']} | {esc(r['m'])} | {r['p']} |")
lines.append("\n## Open decisions\n\n| Decision | Due | Default if not decided |\n|---|---|---|")
for d in D["decisions"]:
    lines.append(f"| {esc(d['q'])} | {d['by']} | {esc(d['def'])} |")
lines.append("\n## Out of scope until clinical and regulatory evidence exists\n")
lines += [f"- {x}" for x in D["postponed"]]
lines.append("\n> Hosting on Azure does not make Medvya compliant by itself. Qualified legal and clinical review in each market is required before real patient records are processed (P1 for demographics, P2 for clinical data, P3 for audio).")
write("risks-and-decisions.md", "\n".join(lines) + "\n")

# ---------- traceability ----------
lines = [HEADER, "# Traceability\n", "## Screen traceability matrix (PRD v2 §09)\n",
         "| ID | Screen / requirement | Module | Role | Source | PRD phase | Status |\n|---|---|---|---|---|---|---|"]
for r in sorted(D["matrix"], key=lambda r: (r["ph"], r["id"])):
    lines.append(f"| {r['id']} | {esc(r['name'])} | {r['mod']} | {esc(r['role'])} | {r['src']} | {r['ph']} | {r['st']} |")
lines.append(f"\n{D['matrixNote']}\n")
lines.append("## Coverage cards\n\n| Check | Value | Note |\n|---|---|---|")
for c in D["cov"]["cards"]:
    lines.append(f"| {c['t']} | {c['v']} | {esc(c['s'])} |")
lines.append("\n## October 2026 plan checklist → PRD phase\n\n| Item | Source phase | PRD phase | Note |\n|---|---|---|---|")
for r in D["pastedMap"]:
    lines.append(f"| {esc(r['i'])} | {r['src']} | {r['ph']} | {esc(r['n'])} |")
lines.append("\n## Architecture v2 screen inventory (27 groups) → phase\n\n| # | Group | Phase |\n|---|---|---|")
for r in D["archMap"]:
    lines.append(f"| {r['n']} | {esc(r['i'])} | {r['ph']} |")
lines.append("\n## Gap analysis items → phase\n\n| Item | Priority | Phase |\n|---|---|---|")
for r in D["gapMap"]:
    lines.append(f"| {esc(r['i'])} | {r['pr']} | {r['ph']} |")
write("traceability.md", "\n".join(lines) + "\n")

# ---------- completeness + findings ----------
lines = [HEADER, "# PRD audit findings and completeness check\n", "## Findings from the PRD v2 review\n"]
for f in D["findings"]:
    lines.append(f"- **{f['k']} · {f['t']}.** {f['d']}")
lines.append("\n## Completeness check (PRD v2 §09b)\n\n| Area | Item | Status | Where |\n|---|---|---|---|")
for r in D["completeness"]:
    lines.append(f"| {r['c']} | {esc(r['i'])} | {r['s']} | {esc(r['w'])} |")
write("completeness-and-findings.md", "\n".join(lines) + "\n")

# ---------- stack + db security (also used by architecture docs) ----------
lines = [HEADER, "# Technology baseline (PRD v2 §07, §07b)\n", "| Layer | Decision | Why / reconciliation | From |\n|---|---|---|---|"]
for s in D["stack"]:
    lines.append(f"| {s['l']} | {esc(s['d'])} | {esc(s['w'])} | {s['p']} |")
lines.append("\n## Database comparison\n\n| Criterion | Azure SQL Database | PostgreSQL Flexible | Cosmos DB |\n|---|---|---|---|")
for r in D["dbCompare"]:
    lines.append(f"| {r['k']} | {esc(r['a'])} | {esc(r['b'])} | {esc(r['c'])} |")
lines.append("\n## Twelve layers of data protection (in place before the first real record in P1)\n\n| # | Layer | Control |\n|---|---|---|")
for l in D["secLayers"]:
    lines.append(f"| {l['n']} | {l['k']} | {esc(l['d'])} |")
lines.append("\n**Per country and per customer:** one logical server per country (Central India, UAE North), each with its own keys, backups and logs. Clinics share an elastic pool, separated by row-level security. From P7, hospitals get a dedicated database and their own customer-managed key. No patient data crosses countries.")
write("technology-and-db-security.md", "\n".join(lines) + "\n")
