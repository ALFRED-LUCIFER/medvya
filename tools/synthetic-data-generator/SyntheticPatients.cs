    // Real-format mobile numbers could belong to someone, so the reminder consent (never granted here) is the control: a patient without a consent receipt is never messaged.
    static string Mobile(int mrn) => "+91" + (9_000_000_000L + mrn).ToString(CultureInfo.InvariantCulture);

    static string Pick(Random r, string[] names, bool variants) { var n = names[r.Next(names.Length)].Split('/'); return variants ? n[r.Next(n.Length)] : n[0]; }

    /// <summary>Patient number <paramref name="n"/> (0-based) of <paramref name="tenant"/>: the same input always gives the same patient.</summary>
    public static SyntheticPatient Generate(Guid tenant, int mrnStart, int n, DateTimeOffset registeredBase)
    {
        var mrn = mrnStart + n;
        var r = new Random(unchecked(mrn * 7919 + 13));
        var roll = r.Next(100);
        var c = Communities[0];
        for (var i = 0; i < Communities.Length; i++) { if (roll < Communities[i].Share) { c = Communities[i]; break; } roll -= Communities[i].Share; }
        var female = r.Next(100) < 51;
        var given = Pick(r, female ? c.Female : c.Male, variants: true);
        var family = Pick(r, c.Family, variants: true);
        var middle = r.Next(100) < 25 ? $"{(char)('A' + r.Next(26))}. " : "";
        var full = $"{given} {middle}{family}";
        string? arabic = null;
        if (c.Family.Contains("Khan") && r.Next(100) < 15 && Arabic.TryGetValue(given.Split(' ')[0], out var ag) && Arabic.TryGetValue(family, out var af)) arabic = $"{ag} {af}";
        else if (c.Family.Contains("Sharma") && r.Next(100) < 5 && Devanagari.TryGetValue(given, out var dg) && Devanagari.TryGetValue(family, out var df)) full = $"{dg} {df}";
        // Ages 0 to 90, triangular around 45: the sum of two uniform draws.
        var age = r.Next(0, 46) + r.Next(0, 46);
        var dob = new DateOnly(2026, 1, 1).AddDays(-(age * 365 + r.Next(365)));
        var place = c.Places[r.Next(c.Places.Length)];
        var complete = r.Next(100) >= 10;
        return new(Guid.CreateVersion7(), mrn.ToString("D6", CultureInfo.InvariantCulture), full, arabic, dob, female ? "Female" : "Male", Mobile(mrn), complete,
            $"{1 + r.Next(240)}, {Streets[r.Next(Streets.Length)]}", place.City, place.District, place.Region, place.Pin, registeredBase.AddMinutes(10 * n));
    }

    /// <summary>The practice and facility ids are derived from the name, so the same name always means the same practice.</summary>
    public static (Guid Tenant, Guid Facility) Ids(string practice)
    {
        var h = SHA256.HashData(Encoding.UTF8.GetBytes("medvya-synthetic-practice:" + practice));
        var t = new Guid(h.AsSpan(0, 16)); var f = new Guid(h.AsSpan(16, 16));
        return (t, f);
    }

    internal static Guid PatientId(Guid tenant, string mrn) => new(SHA256.HashData(Encoding.UTF8.GetBytes(tenant + ":" + mrn)).AsSpan(0, 16));

    public static void EnsureAllowed(string? environment, string practice, int count, int mrnStart)
    {
        SyntheticSeed.EnsureNonProduction(environment);
        if (string.IsNullOrWhiteSpace(practice) || practice.Length > 150 || LooksLikeProduction().IsMatch(practice))
            throw new InvalidOperationException("Synthetic seeding refused: the practice name is empty, too long, or looks like a production name.");
        if (count is < 1 or > 999_999 || mrnStart < 1 || mrnStart + count - 1 > 999_999)
            throw new ArgumentOutOfRangeException(nameof(count), "count must be 1 to 999,999 and every MRN must fit six digits.");
    }

    /// <summary>
    /// Seeds <paramref name="count"/> patients with MRNs from <paramref name="mrnStart"/> into the synthetic practice <paramref name="practice"/> (created, marked "(synthetic)", on first use).
    /// A re-run adds only the missing MRNs. <paramref name="resetConnectionString"/> (an owner-capable login: the application role may not DELETE) deletes that practice's patients first.
    /// Returns the patient ids of this run's MRN range in order.
    /// </summary>
    public static async Task<(Guid Tenant, Guid Facility, Guid[] Ids, int Added)> SeedAsync(string connectionString, string? environment, string practice, int count, int mrnStart,
        string? resetConnectionString = null, Guid? memberUserId = null, string region = "centralindia", CancellationToken ct = default)
    {
        EnsureAllowed(environment, practice, count, mrnStart);
        var (tenant, facility) = Ids(practice);
        var name = practice + SyntheticSeed.Marker;

        await using (var db = SyntheticSeed.Tenancy(connectionString, tenant))
        {
            var existing = await db.Tenants.FindAsync([tenant], ct);
            if (existing is not null && existing.Name != name) throw new InvalidOperationException("Synthetic seeding refused: that practice exists and is not marked synthetic.");
            if (existing is null) db.Tenants.Add(new Tenant { Id = tenant, Name = name, CountryCode = "IN", ResidencyRegion = region });
            if (await db.Facilities.FindAsync([facility], ct) is null) db.Facilities.Add(new Facility { Id = facility, TenantId = tenant, Name = "Main" + SyntheticSeed.Marker, TimeZone = "Asia/Kolkata" });
            if (memberUserId is { } u && !await db.Memberships.AnyAsync(m => m.UserId == u, ct))
                db.Memberships.Add(new Membership { Id = Guid.CreateVersion7(), TenantId = tenant, UserId = u, FacilityId = facility, Role = Role.Receptionist, Status = MembershipStatus.Active });
            await db.SaveChangesAsync(ct);
        }

        if (resetConnectionString is not null) await ResetAsync(resetConnectionString, tenant, ct);

        var all = new SyntheticPatient[count];
        var registeredBase = DateTimeOffset.UtcNow.AddMinutes(-10.0 * count);
        for (var n = 0; n < count; n++) all[n] = Generate(tenant, mrnStart, n, registeredBase);
        all = [.. all.Select(p => p with { Id = PatientId(tenant, p.Mrn) })];

        await using var conn = await PostgresDataSources.For(connectionString).OpenConnectionAsync(ct);
        await using var tx = await conn.BeginTransactionAsync(ct);
        await Exec(conn, "SELECT set_config('medvya.tenant_id', @t, true)", ct, ("t", tenant.ToString()));
        var have = new HashSet<string>(StringComparer.Ordinal);
        await using (var read = new NpgsqlCommand("""SELECT "Mrn" FROM patients."Patients" WHERE "FacilityId" = @f""", conn, tx))
        {
            read.Parameters.AddWithValue("f", facility);
            await using var rd = await read.ExecuteReaderAsync(ct);
            while (await rd.ReadAsync(ct)) have.Add(rd.GetString(0));
        }
        var missing = all.Where(p => !have.Contains(p.Mrn)).ToArray();

        var ids = missing.Select(p => p.Id).ToArray();
        await Insert(conn, "Patients", [
            ("Id", NpgsqlDbType.Uuid, ids), ("TenantId", NpgsqlDbType.Uuid, missing.Select(_ => tenant).ToArray()), ("FacilityId", NpgsqlDbType.Uuid, missing.Select(_ => facility).ToArray()),
            ("Mrn", NpgsqlDbType.Varchar, missing.Select(p => p.Mrn).ToArray()), ("CountryCode", NpgsqlDbType.Char, missing.Select(_ => "IN").ToArray()),
            ("FullName", NpgsqlDbType.Varchar, missing.Select(p => p.FullName).ToArray()), ("ArabicName", NpgsqlDbType.Varchar, missing.Select(p => p.ArabicName).ToArray()),
            ("DateOfBirth", NpgsqlDbType.Date, missing.Select(p => p.DateOfBirth).ToArray()), ("DateOfBirthEstimated", NpgsqlDbType.Boolean, missing.Select(_ => false).ToArray()),
            ("SexAtBirth", NpgsqlDbType.Varchar, missing.Select(p => p.Sex).ToArray()), ("PreferredLanguage", NpgsqlDbType.Varchar, missing.Select(_ => "en").ToArray()),
            ("Mobile", NpgsqlDbType.Varchar, missing.Select(p => p.Mobile).ToArray()), ("Status", NpgsqlDbType.Varchar, missing.Select(p => p.Complete ? "Complete" : "Incomplete").ToArray()),
            ("RegisteredAt", NpgsqlDbType.TimestampTz, missing.Select(p => p.RegisteredAt.UtcDateTime).ToArray()), ("ChangedAt", NpgsqlDbType.TimestampTz, missing.Select(p => p.RegisteredAt.UtcDateTime).ToArray()),
            ("Address_Line1", NpgsqlDbType.Varchar, missing.Select(p => p.Line1).ToArray()), ("Address_City", NpgsqlDbType.Varchar, missing.Select(p => p.City).ToArray()),
            ("Address_District", NpgsqlDbType.Varchar, missing.Select(p => p.District).ToArray()), ("Address_Region", NpgsqlDbType.Varchar, missing.Select(p => p.Region).ToArray()),
            ("Address_PostalCode", NpgsqlDbType.Varchar, missing.Select(p => p.PostalCode).ToArray()),
        ], ct);
        // A complete registration has a payer and an emergency contact (PatientRegistry.StatusFor); the contact's number is the patient's own fake one.
        var complete = missing.Where(p => p.Complete).ToArray();
        await Insert(conn, "PayerCoverages", [
            ("Id", NpgsqlDbType.Uuid, complete.Select(_ => Guid.CreateVersion7()).ToArray()), ("TenantId", NpgsqlDbType.Uuid, complete.Select(_ => tenant).ToArray()),
            ("PatientId", NpgsqlDbType.Uuid, complete.Select(p => p.Id).ToArray()), ("Kind", NpgsqlDbType.Varchar, complete.Select(_ => "SelfPay").ToArray()),
        ], ct);
        await Insert(conn, "Relationships", [
            ("Id", NpgsqlDbType.Uuid, complete.Select(_ => Guid.CreateVersion7()).ToArray()), ("TenantId", NpgsqlDbType.Uuid, complete.Select(_ => tenant).ToArray()),
            ("PatientId", NpgsqlDbType.Uuid, complete.Select(p => p.Id).ToArray()), ("Name", NpgsqlDbType.Varchar, complete.Select(p => p.FullName.Split(' ')[^1]).ToArray()),
            ("Relationship", NpgsqlDbType.Varchar, complete.Select(_ => "Other").ToArray()), ("Phone", NpgsqlDbType.Varchar, complete.Select(p => p.Mobile).ToArray()),
            ("IsEmergencyContact", NpgsqlDbType.Boolean, complete.Select(_ => true).ToArray()), ("IsGuardian", NpgsqlDbType.Boolean, complete.Select(_ => false).ToArray()),
        ], ct);
        // The next registration by the API must not reuse a seeded MRN.
        await Exec(conn, """
            INSERT INTO patients."MrnCounters" ("TenantId","FacilityId","LastNumber") VALUES (@t, @f, @last)
            ON CONFLICT ("TenantId","FacilityId") DO UPDATE SET "LastNumber" = GREATEST(patients."MrnCounters"."LastNumber", EXCLUDED."LastNumber")
            """, ct, ("t", tenant), ("f", facility), ("last", mrnStart + count - 1));
        await tx.CommitAsync(ct);
        // Planner statistics for the new rows; autovacuum does it within a minute where the role may not ANALYZE.
        try { await Exec(conn, "ANALYZE patients.\"Patients\"", ct); } catch (PostgresException e) when (e.SqlState == PostgresErrorCodes.InsufficientPrivilege) { }
        return (tenant, facility, [.. all.Select(p => p.Id)], missing.Length);
    }

    /// <summary>Deletes the synthetic practice's patients and what hangs off them (it cannot touch another tenant: the tenant setting and the filter both name this one).</summary>
    static async Task ResetAsync(string resetConnectionString, Guid tenant, CancellationToken ct)
    {
        await using var conn = await PostgresDataSources.For(resetConnectionString).OpenConnectionAsync(ct);
        await using var tx = await conn.BeginTransactionAsync(ct);
        await Exec(conn, "SET LOCAL ROLE medvya_owner", ct); // owner: the application role holds no DELETE; row-level security still binds the owner
        await Exec(conn, "SELECT set_config('medvya.tenant_id', @t, true)", ct, ("t", tenant.ToString()));
        foreach (var table in new[] { "Relationships", "PayerCoverages", "Identifiers", "MergeRequests", "Patients" })
            await Exec(conn, $"""DELETE FROM patients."{table}" WHERE "TenantId" = @t""", ct, ("t", tenant));
        await Exec(conn, """DELETE FROM patients."MrnCounters" WHERE "TenantId" = @t""", ct, ("t", tenant));
        await tx.CommitAsync(ct);
    }

    /// <summary>Multi-row INSERT from column arrays in chunks. COPY is refused for roles bound by row-level security, so this is the fast path the application role has.</summary>
    static async Task Insert(NpgsqlConnection conn, string table, (string Column, NpgsqlDbType Type, Array Values)[] columns, CancellationToken ct)
    {
        const int Chunk = 5000;
        var rows = columns[0].Values.Length;
        var names = string.Join(", ", columns.Select(c => $"\"{c.Column}\""));
        var from = string.Join(", ", columns.Select((c, i) => $"@p{i}"));
        for (var at = 0; at < rows; at += Chunk)
        {
            await using var cmd = new NpgsqlCommand($"INSERT INTO patients.\"{table}\" ({names}) SELECT * FROM unnest({from})", conn);
            for (var i = 0; i < columns.Length; i++)
            {
                var slice = Array.CreateInstance(columns[i].Values.GetType().GetElementType()!, Math.Min(Chunk, rows - at));
                Array.Copy(columns[i].Values, at, slice, 0, slice.Length);
                cmd.Parameters.Add(new NpgsqlParameter($"p{i}", NpgsqlDbType.Array | columns[i].Type) { Value = slice });
            }
            await cmd.ExecuteNonQueryAsync(ct);
        }
    }

    static async Task Exec(NpgsqlConnection conn, string sql, CancellationToken ct, params (string Name, object Value)[] args)
    {
        await using var cmd = new NpgsqlCommand(sql, conn);
        foreach (var (name, value) in args) cmd.Parameters.AddWithValue(name, value);
        await cmd.ExecuteNonQueryAsync(ct);
    }
