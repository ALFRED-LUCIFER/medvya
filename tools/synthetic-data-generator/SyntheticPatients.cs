/// <summary>
/// Bulk-seeds one named synthetic practice with synthetic patients: realistic Indian names with common spelling variants, sequential MRNs,
/// age and sex spread, address, a self-pay payer and an emergency contact. Written as the application role by multi-row INSERT (COPY is refused under row-level security) inside the tenant,
/// so row-level security's block predicates, the unique MRN index and the MRN counter hold as for the API. What COPY skips on purpose:
/// the per-patient "patient.register" audit events (the hash-chain trigger makes 40,000 of them minutes slow, and these patients were not registered by a person),
/// consent receipts (so no reminder channel is ever granted), national identifiers (none, so there is nothing to encrypt), the idempotency key and registration-time duplicate review.
/// Search columns are generated by the database (see the PatientSearchKey migration), so COPY fills them too.
/// </summary>
